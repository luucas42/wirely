#!/usr/bin/env swift
// Usage: swift scripts/make-landmask.swift <ne_50m_land.geojson> <out.swift>
// Rasterises Natural Earth land polygons into a 720x360 equirectangular bitmap
// (0.5 deg cells, row 0 = 90N, col 0 = 180W) and writes it as a packed-bit Swift file.
import Foundation
import CoreGraphics

let args = CommandLine.arguments
guard args.count == 3 else {
    FileHandle.standardError.write(Data("usage: make-landmask.swift <in.geojson> <out.swift>\n".utf8))
    exit(2)
}
let W = 720, H = 360

guard let data = try? Data(contentsOf: URL(fileURLWithPath: args[1])),
      let root = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
      let features = root["features"] as? [[String: Any]] else {
    FileHandle.standardError.write(Data("cannot read GeoJSON\n".utf8))
    exit(1)
}

let path = CGMutablePath()
func addRing(_ ring: [[Double]]) {
    guard ring.count > 2 else { return }
    for (i, c) in ring.enumerated() {
        let p = CGPoint(x: (c[0] + 180) * 2, y: (c[1] + 90) * 2)
        if i == 0 { path.move(to: p) } else { path.addLine(to: p) }
    }
    path.closeSubpath()
}
func addPolygon(_ rings: [[[Double]]]) { rings.forEach(addRing) }

for f in features {
    guard let g = f["geometry"] as? [String: Any], let type = g["type"] as? String else { continue }
    switch type {
    case "Polygon":
        if let c = g["coordinates"] as? [[[Double]]] { addPolygon(c) }
    case "MultiPolygon":
        if let c = g["coordinates"] as? [[[[Double]]]] { c.forEach(addPolygon) }
    default: break
    }
}

var pixels = [UInt8](repeating: 0, count: W * H)
pixels.withUnsafeMutableBytes { buf in
    let ctx = CGContext(data: buf.baseAddress, width: W, height: H, bitsPerComponent: 8, bytesPerRow: W,
                        space: CGColorSpaceCreateDeviceGray(),
                        bitmapInfo: CGImageAlphaInfo.none.rawValue)!
    ctx.setShouldAntialias(false)
    ctx.setFillColor(gray: 1, alpha: 1)
    ctx.addPath(path)
    ctx.fillPath(using: .evenOdd)
}

// Bitmap memory is top-down: row 0 = top = 90N.
var packed = [UInt8](repeating: 0, count: W * H / 8)
for i in 0..<(W * H) where pixels[i] > 127 {
    packed[i / 8] |= UInt8(0x80 >> (i % 8))
}
let b64 = Data(packed).base64EncodedString()

let out = """
// Generated by scripts/make-landmask.swift from Natural Earth ne_50m_land. Do not edit.
import Foundation

public enum LandMask {
    static let width = \(W)
    static let height = \(H)

    private static let base64 = "\(b64)"

    private static let bits: [UInt8] = [UInt8](Data(base64Encoded: base64) ?? Data())

    /// 720x360 cells of 0.5 deg; row 0 = 90N..89.5N, col 0 = 180W..179.5W.
    public static func isLand(lat: Double, lon: Double) -> Bool {
        guard lat >= -90, lat <= 90 else { return false }
        var l = lon
        while l >= 180 { l -= 360 }
        while l < -180 { l += 360 }
        let row = min(height - 1, max(0, Int((90 - lat) * 2)))
        let col = min(width - 1, max(0, Int((l + 180) * 2)))
        let i = row * width + col
        guard i / 8 < bits.count else { return false }
        return bits[i / 8] & UInt8(0x80 >> (i % 8)) != 0
    }
}

"""
try out.write(toFile: args[2], atomically: true, encoding: .utf8)
print("land cells: \(pixels.filter { $0 > 127 }.count) / \(W * H); bytes: \(packed.count)")
